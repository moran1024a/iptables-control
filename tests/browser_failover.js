const {chromium}=require(process.env.PLAYWRIGHT_MODULE);
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.TEST_BROWSER||'/opt/google/chrome/chrome',headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[],writes=[];
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('request',r=>{if(r.url().includes('/api/')&&r.method()!=='GET')writes.push(r.url());});
  const middle=()=>page.locator('[data-graph-node="v3"] .graph-node-body');
  const popover=()=>page.locator('[data-failover-popover]');
  try{
    await page.goto(process.env.TEST_URL);
    await page.locator('[name=username]').fill('admin');await page.locator('[name=password]').fill('admin_pass');
    await page.locator('form button.primary').click();
    await page.locator('[data-nav=nodes]').waitFor();
    await page.goto(process.env.TEST_URL+'#/settings');
    const input=page.locator('[name=failover_offline_seconds]');
    await input.waitFor();
    if(await input.inputValue()!=='60')throw new Error('Default timeout is not 60');
    await input.fill('5');
    if(await input.evaluate(el=>el.checkValidity()))throw new Error('Too-short timeout accepted');
    await input.fill('30');
    await page.locator('[data-form=failover-settings] button').click();
    await page.waitForFunction(()=>!document.querySelector('[data-form=failover-settings] button').disabled);
    await page.reload();await input.waitFor();
    if(await input.inputValue()!=='30')throw new Error('Timeout was not persisted');
    await page.goto(process.env.TEST_URL+'#/routes/'+process.env.TEST_ROUTE);
    await middle().waitFor();
    writes.length=0;
    const initial=await page.evaluate(()=>JSON.stringify(canvasView.link.configurations.map(c=>[c.id,c.active_path,c.pending_path,c.state])));
    const geometry=await page.evaluate(()=>[...document.querySelectorAll('[data-runtime-route] .graph-route-line')].map(p=>p.getAttribute('d')));
    await page.locator('[data-graph-node="v1"] .graph-node-body').hover();await page.waitForTimeout(350);
    if(await popover().isVisible())throw new Error('Entry triggered failure preview');
    await page.locator('[data-graph-node="t1"] .graph-node-body').hover();await page.waitForTimeout(350);
    if(await popover().isVisible())throw new Error('Target triggered failure preview');
    await middle().hover();
    await page.waitForFunction(()=>document.querySelectorAll('[data-failover-choice]').length===4);
    await page.locator('.graph-failover-line').first().waitFor();
    if(JSON.stringify(await page.evaluate(()=>[...document.querySelectorAll('[data-runtime-route] .graph-route-line')].map(p=>p.getAttribute('d'))))!==JSON.stringify(geometry))throw new Error('Preview rerouted live lines');
    const rows=page.locator('[data-failover-choice]');
    const blocked=rows.filter({hasText:'无可用备用路径'});
    if(await blocked.count()!==1)throw new Error('Per-target backup availability was lost');
    await blocked.hover();
    if(await page.locator('.graph-failover-line').count())throw new Error('Unavailable row retained another path');
    await rows.first().focus();
    await page.evaluate(()=>{window.focusedPreview=document.activeElement;return refresh();});
    if(!await page.evaluate(()=>document.activeElement===window.focusedPreview))throw new Error('Refresh replaced the focused preview row');
    await page.locator('.graph-failover-line').first().waitFor();
    if(process.env.TEST_SCREENSHOT)await page.screenshot({path:process.env.TEST_SCREENSHOT,fullPage:true});
    if(initial!==await page.evaluate(()=>JSON.stringify(canvasView.link.configurations.map(c=>[c.id,c.active_path,c.pending_path,c.state]))))throw new Error('Hover changed a configuration');
    if(writes.length)throw new Error('Hover issued a mutation: '+writes.join(','));
    await page.keyboard.press('Escape');
    await popover().waitFor({state:'hidden'});
    await page.locator('[data-graph-node="v7"] .graph-node-body').hover();
    await page.waitForFunction(()=>document.querySelector('[data-failover-popover]')?.textContent.includes('被动节点不参与'));
    await page.keyboard.press('Escape');
    await page.route('**/failover-preview?**',async route=>{
      if(new URL(route.request().url()).searchParams.get('vertex')==='v3')await new Promise(r=>setTimeout(r,600));
      await route.continue().catch(()=>{});
    });
    await middle().hover();await page.waitForTimeout(300);
    await page.locator('[data-graph-node="v6"] .graph-node-body').hover();
    await page.waitForFunction(()=>document.querySelector('[data-failover-popover]')?.textContent.includes('当前没有使用此节点'));
    await page.waitForTimeout(700);
    if(!await popover().innerText().then(t=>t.includes('未使用 F')))throw new Error('Stale response replaced the new node preview');
    await page.locator('[data-action=link-edit]').first().click();
    await middle().hover();await page.waitForTimeout(350);
    if(await popover().count())throw new Error('Editing enabled failure preview');
    if(errors.length)throw new Error(errors.join('\n'));
    console.log('PASS: persisted timeout, independent pair previews, immutable live routes, focus preservation, stale response cancellation and edit isolation');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
